def place_grounded(base, prod, width, cx, bottom):
    """Place the console with a shadow cast from its own silhouette: a tight
    contact shadow plus a soft spread, so it sits on the surface."""
    p = scale(prod, width / prod.width)
    p = tone(p, gain=(0.95, 0.95, 0.97))
    x = int(cx - p.width / 2); y = int(bottom - p.height)
    a = np.array(p)[..., 3].astype(np.float32) / 255
    out = base.convert('RGBA')
    for off, blur, op in ((14, 10, 0.75), (46, 60, 0.55)):
        m = Image.new('L', out.size, 0)
        m.paste(Image.fromarray((a * 255).astype(np.uint8)), (x, y + off))
        m = m.filter(ImageFilter.GaussianBlur(blur))
        sh = Image.new('RGBA', out.size, (0, 0, 0, 0))
        sh.putalpha(m.point(lambda v: int(v * op)))
        out = Image.alpha_composite(out, sh)
    out.alpha_composite(p, (x, y))
    return out


for i, (name, (path, width, bottom, glows, bcols, grad, surf, wood, spec)) in enumerate(SCENES.items()):
    c = gradient(*grad)
    for g in glows:
        glow(c, *g)
    bokeh(c, 30, bcols, 30, 130, 60, 720, 0.10, 0.45, seed=20 + i)
    surface(c, 780, surf[0], surf[1], spec=spec, wood=wood, seed=i)
    img = to_img(c)
    prod = product(path)
    img = place_grounded(img, prod, width, 1920, bottom)
    finish(img, name, vignette=0.28)
    print(name)
